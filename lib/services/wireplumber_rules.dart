import 'dart:io';

import '../domain/audio_models.dart';

/// Experimental PipeWire/WirePlumber 0.5+ node description overrides.
/// Requires explicit opt-in and a manual WirePlumber restart to take effect.
/// Does not edit or restart any user/system process and never needs root.
class WirePlumberRules {
  WirePlumberRules({String? configHome})
      : configHome = configHome ?? _configHome();

  final String configHome;
  static const signature = '# Managed by Sound Labels — do not edit this file';

  static String _configHome() {
    final xdg = Platform.environment['XDG_CONFIG_HOME'];
    if (xdg != null && xdg.startsWith('/')) return xdg;
    final home = Platform.environment['HOME'];
    if (home == null || !home.startsWith('/')) {
      throw const FileSystemException('HOME or XDG_CONFIG_HOME is required');
    }
    return '$home/.config';
  }

  File get _file => File(
      '$configHome/wireplumber/wireplumber.conf.d/90-sound-labels.conf');

  static String _quote(String input) {
    if (RegExp(r'[\x00-\x1f\x7f]').hasMatch(input)) {
      throw FormatException('Invalid control character in audio property');
    }
    return '"${input.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"';
  }

  Future<void> _assertCompatible() async {
    try {
      final result = await Process.run('wireplumber', ['--version']);
      if (result.exitCode != 0) {
        throw StateError('WirePlumber was not detected');
      }
      final match = RegExp(r'(\d+)\.(\d+)').firstMatch(result.stdout.toString());
      if (match == null) throw StateError('WirePlumber version unknown');
      final major = int.parse(match.group(1)!);
      final minor = int.parse(match.group(2)!);
      if (major == 0 && minor < 5) {
        throw StateError('WirePlumber 0.5+ is required');
      }
    } on ProcessException {
      throw StateError('WirePlumber command is unavailable');
    }
  }

  String _buildRules(Map<String, DeviceOverride> overrides) {
    final groups = <String, List<String>>{
      'monitor.alsa.rules': [],
      'monitor.bluez.rules': [],
    };
    final keys = overrides.keys.toList()..sort();
    for (final key in keys) {
      final override = overrides[key]!;
      if (!override.systemWide || override.alias == null || override.alias!.isEmpty) {
        continue;
      }
      // Disallow arbitrary match expressions: only stable ALSA/BlueZ node names.
      final separator = key.indexOf(':');
      if (separator <= 0) throw StateError('Invalid endpoint key: $key');
      final nodeName = key.substring(separator + 1);
      final group = nodeName.startsWith('alsa_')
          ? 'monitor.alsa.rules'
          : nodeName.startsWith('bluez_')
              ? 'monitor.bluez.rules'
              : null;
      if (group == null) {
        throw StateError('Host-level rename supports ALSA and BlueZ nodes only');
      }
      final alias = _quote(override.alias!);
      groups[group]!.add('''  {
    matches = [ { node.name = ${_quote(nodeName)} } ]
    actions = { update-props = {
      node.description = $alias
      node.nick = $alias
    } }
  }''');
    }

    final output = StringBuffer('$signature\n'
        '# Experimental: user must restart WirePlumber and verify desktop menus.\n');
    for (final entry in groups.entries) {
      if (entry.value.isNotEmpty) {
        output.writeln('${entry.key} = [');
        output.writeln(entry.value.join('\n'));
        output.writeln(']');
      }
    }
    return output.toString();
  }

  Future<void> replace(Map<String, DeviceOverride> overrides) async {
    final content = _buildRules(overrides); // Validate all before touching disk.
    final file = _file;
    if (await file.exists()) {
      final existing = await file.readAsString();
      if (!existing.startsWith(signature)) {
        throw StateError('An unmanaged 90-sound-labels.conf already exists');
      }
    }
    if (content.trim() ==
        '$signature\n# Experimental: user must restart WirePlumber and verify desktop menus.') {
      // No rules left. Preserve the prior managed file as a recoverable backup.
      if (await file.exists()) {
        await file.rename('${file.path}.bak');
      }
      return;
    }
    await _assertCompatible();
    await file.parent.create(recursive: true);
    final temporary = File('${file.path}.tmp');
    try {
      await temporary.writeAsString(content, flush: true);
      if (await file.exists()) {
        await file.copy('${file.path}.bak');
      }
      await temporary.rename(file.path);
    } catch (_) {
      if (await temporary.exists()) await temporary.delete();
      rethrow;
    }
  }
}
